/**
 * Função utilitária para desenhar qualquer sprite matricial no canvas
 */
function drawSprite(ctx, spriteMatrix, x, y, scale = 1, color = null) {
  if (!spriteMatrix || !spriteMatrix.length) return;
  const originalFill = ctx.fillStyle;
  if (color) ctx.fillStyle = color;

  const rows = spriteMatrix.length;
  const cols = spriteMatrix[0].length;

  for (let r = 0; r < rows; r++) {
    const rowStr = spriteMatrix[r];
    for (let c = 0; c < cols; c++) {
      if (rowStr[c] === '1') {
        ctx.fillRect(
          Math.floor(x + c * scale),
          Math.floor(y + r * scale),
          scale,
          scale
        );
      }
    }
  }

  if (color) ctx.fillStyle = originalFill;
}

window.SPRITES = SPRITES;
window.drawSprite = drawSprite;
